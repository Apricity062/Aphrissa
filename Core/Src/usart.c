#include "time_service.h"

/* 单字节接收缓冲 (必须静态, HAL 中断会持续写入) */
static uint8_t s_rx_byte;

/* 启动 USART1 单字节中断接收 (校时帧逐字节喂给时间服务层) */
void USART1_StartRx(void) {
  /* USART1 全局中断: 优先级 2 (低于 TIM3=1, 高于默认), 使能 NVIC */
  HAL_NVIC_SetPriority(USART1_IRQn, 2, 0);
  HAL_NVIC_EnableIRQ(USART1_IRQn);
  HAL_UART_Receive_IT(&huart1, &s_rx_byte, 1);
}

/* 每收到一个字节回调一次: 喂给行缓冲, 收满一行后由主循环解析 */
void HAL_UART_RxCpltCallback(UART_HandleTypeDef *huart) {
  if (huart->Instance == USART1) {
    TimeService_UartRxByte(s_rx_byte);
    HAL_UART_Receive_IT(&huart1, &s_rx_byte, 1); /* 重新挂接收 */
  }
}

