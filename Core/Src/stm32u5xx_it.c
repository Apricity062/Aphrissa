/**
 * @brief  TIM3 周期中断回调 (1ms): 维护硬件时基 + 帧率 + 心跳。
 *         只做轻量计数/置标志, 严禁在此做 I2C/SPI/UI 操作。
 */
void HAL_TIM_PeriodElapsedCallback(TIM_HandleTypeDef *htim)
{
  if (htim->Instance == TIM3) {
    hw_ms++;                                   /* 硬件毫秒时基 */

    Backlight_Tick();                          /* 背光软件PWM (LCD_BL=PB10) */
    Buzzer_Tick();                             /* 蜂鸣器响铃节奏 (响0.5s停0.5s) */

    /* 每 33ms 硬件触发一次 VSYNC(≈30fps), 帧率不再依赖主循环 HAL_Delay 忙等 */
    static uint32_t last_vsync = 0;
    if ((uint32_t)(hw_ms - last_vsync) >= 33u) {
      last_vsync = hw_ms;
      TouchGFX_SignalVSync();                  /* 裸机下仅置标志, 中断安全 */
    }

    /* 每 500ms 翻转心跳 LED */
    static uint32_t last_hb = 0;
    if ((uint32_t)(hw_ms - last_hb) >= 500u) {
      last_hb = hw_ms;
      HAL_GPIO_TogglePin(GPIOC, GPIO_PIN_13);
    }
  }
}

